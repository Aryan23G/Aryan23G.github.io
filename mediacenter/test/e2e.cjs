// static server with HTTP Range support (needed for seeking)
const server = http.createServer((req, res) => {
  let p = decodeURIComponent(new URL(req.url, 'http://x').pathname); if (p.endsWith('/')) p += 'index.html';
  const f = path.join(ROOT, p.replace(/^\/mediacenter/, ''));
  if (!f.startsWith(ROOT) || !fs.existsSync(f)) { res.writeHead(404); return res.end(); }
  const type = { '.html':'text/html', '.js':'text/javascript', '.png':'image/png', '.webmanifest':'application/manifest+json' }[path.extname(f)] || 'application/octet-stream';
  res.writeHead(200, { 'content-type': type }); fs.createReadStream(f).pipe(res);
});
const ranged = (route, file, type) => {
  const buf = fs.readFileSync(file), rg = route.request().headers()['range'];
  if (!rg) return route.fulfill({ body: buf, headers: { 'accept-ranges':'bytes', 'content-type': type } });
  let [a, e] = rg.replace('bytes=', '').split('-'); a = +a; e = e ? +e : buf.length - 1;
  route.fulfill({ status: 206, body: buf.subarray(a, e + 1), headers: { 'accept-ranges':'bytes', 'content-range':`bytes ${a}-${e}/${buf.length}`, 'content-type': type } });
};

